import unreal
from editor_toolset.toolsets.blueprint import BlueprintTools as B
bp=unreal.load_asset('/Game/AIExample/Interaction/BP_InteractionTestDoor')
for name in ['AnimationStartYaw','AnimationElapsed','AnimationAlpha','SwingDuration']:
    if name not in B.list_variables(bp):B.add_variable(bp,name,'float')
g=B.get_graph(bp,'OnRep_IsOpen')
for t in ['Class|SceneComponent|GetRelativeRotation','Actor|Tick|SetActorTickEnabled','Math|Float|Clamp(Float)']:
    print('PINS',t,[(p.name,p.type_id) for p in B.get_node_type_pins(g,t).input_pins])
B.write_graph_dsl(g,'''(fn OnRep_IsOpen ()
 (Variables|Default|SetAnimationStartYaw (.yaw (Class|SceneComponent|GetRelativeRotation :self (Variables|Default|GetDoorHinge))))
 (Variables|Default|SetAnimationElapsed 0.0)
 (Actor|Tick|SetActorTickEnabled :bEnabled true))''')
B.write_graph_dsl(B.get_graph(bp,'EventGraph'),'''(event AddEvent|EventTick (DeltaSeconds)
 (Variables|Default|SetAnimationElapsed (+ (Variables|Default|GetAnimationElapsed) DeltaSeconds))
 (Variables|Default|SetAnimationAlpha (Math|Float|Clamp(Float) (/ (Variables|Default|GetAnimationElapsed) (Variables|Default|GetSwingDuration)) 0.0 1.0))
 (bind Alpha (Variables|Default|GetAnimationAlpha))
 (bind Ease (* (* Alpha Alpha) (- 3.0 (* 2.0 Alpha))))
 (bind Start (Variables|Default|GetAnimationStartYaw))
 (bind Target (select (Variables|Default|GetIsOpen) 90.0 0.0))
 (Transformation|SetRelativeRotation :self (Variables|Default|GetDoorHinge)
  :NewRotation (Math|Rotator|MakeRotator :Yaw (+ Start (* (- Target Start) Ease))))
 (if (>= Alpha 1.0)
  (Transformation|SetRelativeRotation :self (Variables|Default|GetDoorHinge) :NewRotation (Math|Rotator|MakeRotator :Yaw Target))
  (Actor|Tick|SetActorTickEnabled :bEnabled false)))''')
B.compile_blueprint(bp)
unreal.get_default_object(bp.generated_class()).set_editor_property('SwingDuration',0.6)
unreal.EditorAssetLibrary.save_loaded_asset(bp)
assert 'SetAnimationStartYaw' in B.read_graph_dsl(B.get_graph(bp,'OnRep_IsOpen'))
assert 'SetRelativeRotation' in B.read_graph_dsl(B.get_graph(bp,'EventGraph'))
print('SMOOTH_DOOR_SAVED',bp.get_editor_property('status'))
