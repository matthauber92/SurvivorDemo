"""Add forgiving, occlusion-tested nearby pickup focus. No attachment changes."""
import unreal,sys,datetime,shutil
from pathlib import Path
sys.path.insert(0,str(Path(unreal.Paths.project_dir())/'MigrationStaging'))
from combat_helpers import *
assert not unreal.EditorLevelLibrary.get_pie_worlds(False)
bp=asset('Interaction/BP_InteractionComponent')
root=Path(unreal.Paths.project_dir());backup=root/'Backups'/('NearbyPickup-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S'));backup.mkdir(parents=True)
shutil.copy2(root/'Content/AIExample/Interaction/BP_InteractionComponent.uasset',backup/'BP_InteractionComponent.uasset')
fn(bp,'ValidateNearbyPickup',[('Target',unreal.Actor.static_class()),('ViewDirection','Vector')],[('Valid','bool')])
fn(bp,'FindNearbyPickup',[],[],[('BestDistance','float')])
B.compile_blueprint(bp,warnings_as_errors=True)
write(bp,'ValidateNearbyPickup','''(fn ValidateNearbyPickup (Target ViewDirection)
 (Utilities|IsValid Target
  (:"Is Valid"
   (bind Pickup (Utilities|Casting|CastToBP_ItemPickup :Object Target)
    (:then
     (bind Pawn (Variables|Default|GetOwnerPawn))
     (bind Offset (- (Transformation|GetActorLocation :self Target) (Transformation|GetActorLocation :self Pawn)))
     (bind (X Y Z) (Math|Vector|BreakVector Offset))
     (bind (DX DY DZ) (Math|Vector|BreakVector ViewDirection))
     (if (and (<= (Math|Vector|VectorLength Offset) (Variables|Default|GetInteractionRange))
              (>= (Math|Vector|DotProduct (Math|Vector|Normalize (Math|Vector|MakeVector X Y 0.0)) (Math|Vector|Normalize (Math|Vector|MakeVector DX DY 0.0))) 0.5))
      (bind (Eyes Rotation) (Actor|GetActorEyesViewPoint :self Pawn))
      (bind (Hit Blocked) (Collision|LineTraceByChannel :Start Eyes :End (Transformation|GetActorLocation :self Target) :ActorsToIgnore (Utilities|Array|MakeArray Pawn)))
      (bind (B I T D L P N IN PM HitActor C HB BN HI E F TS TE) (Collision|BreakHitResult Hit))
      (return (and Blocked (== HitActor Target)))
      (else (return false))))
    (:CastFailed (return false))))
  (:"Is Not Valid" (return false))))''')
write(bp,'FindNearbyPickup','''(fn FindNearbyPickup ()
 (bind Pawn (Variables|Default|GetOwnerPawn))
 (bind PC (Utilities|Casting|CastToPlayerController (Pawn|GetController :self Pawn)))
 (bind Camera (Class|PlayerController|GetPlayerCameraManager :self PC))
 (bind Direction (Math|Vector|GetForwardVector (Camera|GetCameraRotation :self Camera)))
 (Variables|Default|SetBestDistance 251.0)
 (bind Candidates (Actor|GetAllActorsOfClass :ActorClass "/Game/AIExample/Items/BP_ItemPickup.BP_ItemPickup_C"))
 (for i (range (Utilities|Array|Length Candidates))
  (bind Candidate (Utilities|Array|Get(acopy) Candidates i))
  (bind Distance (Math|Vector|VectorLength (- (Transformation|GetActorLocation :self Candidate) (Transformation|GetActorLocation :self Pawn))))
  (if (< Distance (Variables|Default|GetBestDistance))
   (if (CallFunction|ValidateNearbyPickup :Target Candidate :ViewDirection Direction)
    (Variables|Default|SetBestDistance Distance)
    (Variables|Default|SetFocusedActor Candidate)
    (bind Prompt (Class|BPIInteractable|GetInteractionPrompt(Message) :self Candidate :Interactor Pawn))
    (Variables|Default|SetPromptText Prompt)))))''')
write(bp,'ValidateTarget','''(fn ValidateTarget (Target ViewOrigin ViewDirection)
 (Utilities|IsValid Target
  (:"Is Valid"
   (bind Pawn (Variables|Default|GetOwnerPawn))
   (bind PawnLocation (Transformation|GetActorLocation :self Pawn))
   (if (and (<= (Math|Vector|VectorLength (- (Transformation|GetActorLocation :self Target) PawnLocation)) (Variables|Default|GetInteractionRange))
            (<= (Math|Vector|VectorLength (- ViewOrigin PawnLocation)) 850.0))
    (if (CallFunction|ValidateNearbyPickup :Target Target :ViewDirection ViewDirection)
     (return true))
    (bind Direction (Math|Vector|Normalize ViewDirection))
    (bind (Hit DidHit) (Collision|LineTraceByChannel :Start ViewOrigin :End (+ ViewOrigin (* Direction 1100.0)) :ActorsToIgnore (Utilities|Array|MakeArray Pawn)))
    (bind (Blocking Initial Time Distance Location ImpactPoint Normal ImpactNormal PhysMat HitActor HitComponent HitBone Bone HitItem Element Face TraceStart TraceEnd) (Collision|BreakHitResult Hit))
    (if (and DidHit (== HitActor Target))
     (bind (Eyes EyeRotation) (Actor|GetActorEyesViewPoint :self Pawn))
     (bind (SightHit SightBlocked) (Collision|LineTraceByChannel :Start Eyes :End (+ ImpactPoint (* Direction 2.0)) :ActorsToIgnore (Utilities|Array|MakeArray Pawn)))
     (bind (B2 I2 T2 D2 L2 P2 N2 IN2 PM2 SightActor C2 HB2 BN2 HI2 E2 F2 TS2 TE2) (Collision|BreakHitResult SightHit))
     (return (and SightBlocked (== SightActor Target)))
     (else (return false)))
    (else (return false))))
  (:"Is Not Valid" (return false))))''')
write(bp,'UpdateFocus','''(fn UpdateFocus ()
 (Variables|Default|SetFocusedActor "None")
 (Variables|Default|SetPromptText "")
 (bind Pawn (Variables|Default|GetOwnerPawn))
 (if (Pawn|IsLocallyControlled :self Pawn)
  (bind PC (Utilities|Casting|CastToPlayerController (Pawn|GetController :self Pawn)))
  (bind Camera (Class|PlayerController|GetPlayerCameraManager :self PC))
  (bind Origin (Camera|GetCameraLocation :self Camera))
  (bind Direction (Math|Vector|GetForwardVector (Camera|GetCameraRotation :self Camera)))
  (bind (Hit DidHit) (Collision|LineTraceByChannel :Start Origin :End (+ Origin (* Direction 1100.0)) :ActorsToIgnore (Utilities|Array|MakeArray Pawn)))
  (bind (Blocking Initial Time Distance Location ImpactPoint Normal ImpactNormal PhysMat HitActor HitComponent HitBone Bone HitItem Element Face TraceStart TraceEnd) (Collision|BreakHitResult Hit))
  (if DidHit
   (if (CallFunction|ValidateTarget :Target HitActor :ViewOrigin Origin :ViewDirection Direction)
    (Variables|Default|SetFocusedActor HitActor)
    (bind Prompt (Class|BPIInteractable|GetInteractionPrompt(Message) :self HitActor :Interactor Pawn))
    (Variables|Default|SetPromptText Prompt)))
  (if (== (Utilities|String|Len (Utilities|String|ToString(Text) (Variables|Default|GetPromptText))) 0)
   (CallFunction|FindNearbyPickup))))''')
save(bp)
print('NEARBY_PICKUP_SAVED',str(backup))
