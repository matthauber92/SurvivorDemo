import unreal
from editor_toolset.toolsets.blueprint import BlueprintTools as B
bp=unreal.load_asset('/Game/AIExample/Items/BP_InventoryComponent')
def write(name,code):
    g=B.get_graph(bp,name)
    B.write_graph_dsl(g,code)
    actual=B.read_graph_dsl(g)
    assert len(actual)>100,(name,actual)
    print(name,actual)
write('GetItemQuantity','''(fn GetItemQuantity (ItemID)
 (Variables|Default|SetCount 0)
 (for i (range (Utilities|Array|Length (Variables|Default|GetItemIDs)))
  (if (== (Utilities|Array|Get(acopy) (Variables|Default|GetItemIDs) i) ItemID)
   (Variables|Default|SetCount (+ (Variables|Default|GetCount) (Utilities|Array|Get(acopy) (Variables|Default|GetQuantities) i)))))
 (return (Variables|Default|GetCount)))''')
write('CanAddItem','''(fn CanAddItem (Definition Amount)
 (Utilities|IsValid Definition
  (:"Is Valid"
   (bind MaxStack (Class|PDAItemDefinition|GetMaxStackSize :self Definition))
   (bind ID (Class|PDAItemDefinition|GetItemID :self Definition))
   (if (and (> Amount 0) (and (> MaxStack 0) (!= ID "None")))
    (Variables|Default|SetFreeSpace (* (- (Variables|Default|GetMaximumSlots) (Utilities|Array|Length (Variables|Default|GetItemIDs))) MaxStack))
    (for i (range (Utilities|Array|Length (Variables|Default|GetItemIDs)))
     (if (== (Utilities|Array|Get(acopy) (Variables|Default|GetItemIDs) i) ID)
      (Variables|Default|SetFreeSpace (+ (Variables|Default|GetFreeSpace) (- MaxStack (Utilities|Array|Get(acopy) (Variables|Default|GetQuantities) i))))))
    (return (>= (Variables|Default|GetFreeSpace) Amount))
    (else (return false))))
  (:"Is Not Valid" (return false))))''')
write('TryAddItem','''(fn TryAddItem (Definition Amount)
 (if (Networking|HasAuthority :self (Components|GetOwner))
  (if (CallFunction|CanAddItem :Definition Definition :Amount Amount)
   (Variables|Default|SetRemaining Amount)
   (bind ID (Class|PDAItemDefinition|GetItemID :self Definition))
   (bind MaxStack (Class|PDAItemDefinition|GetMaxStackSize :self Definition))
   (for i (range (Utilities|Array|Length (Variables|Default|GetItemIDs)))
    (if (== (Utilities|Array|Get(acopy) (Variables|Default|GetItemIDs) i) ID)
     (Variables|Default|SetTransfer (Math|Integer|Min(Integer) (Variables|Default|GetRemaining) (- MaxStack (Utilities|Array|Get(acopy) (Variables|Default|GetQuantities) i))))
     (Utilities|Array|SetArrayElem (Variables|Default|GetQuantities) i (+ (Utilities|Array|Get(acopy) (Variables|Default|GetQuantities) i) (Variables|Default|GetTransfer)))
     (Variables|Default|SetRemaining (- (Variables|Default|GetRemaining) (Variables|Default|GetTransfer)))))
   (while (> (Variables|Default|GetRemaining) 0)
    (Variables|Default|SetTransfer (Math|Integer|Min(Integer) (Variables|Default|GetRemaining) MaxStack))
    (Utilities|Array|Add (Variables|Default|GetItemIDs) ID)
    (Utilities|Array|Add (Variables|Default|GetQuantities) (Variables|Default|GetTransfer))
    (Variables|Default|SetRemaining (- (Variables|Default|GetRemaining) (Variables|Default|GetTransfer))))
   (return true)
   (else (return false)))
  (else (return false))))''')
B.compile_blueprint(bp)
assert 'BS_UP_TO_DATE' in str(bp.get_editor_property('status'))
unreal.EditorAssetLibrary.save_loaded_asset(bp)

