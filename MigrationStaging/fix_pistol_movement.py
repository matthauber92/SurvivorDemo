import unreal,sys,ast,datetime,shutil
from pathlib import Path
sys.path.insert(0,str(Path(unreal.Paths.project_dir())/'MigrationStaging'))
from combat_helpers import *
assert not unreal.EditorLevelLibrary.get_pie_worlds(False)
root=Path(unreal.Paths.project_dir());backup=root/'Backups'/('PistolMovement-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S'));backup.mkdir(parents=True)
for rel in ['Interaction/BP_SurvivorInteractionCharacter','Combat/Animation/ABP_SurvivorCombat']:
 shutil.copy2(root/'Content/AIExample'/(rel+'.uasset'),backup/(rel.split('/')[-1]+'.uasset'))
bp=asset('Interaction/BP_SurvivorInteractionCharacter')
var(bp,'PistolPoseUntil','float')
B.compile_blueprint(bp,warnings_as_errors=True)
write(bp,'NoteHipFire','''(fn NoteHipFire ()
 (Variables|Default|SetHipFireUntil (+ (Utilities|Time|GetGameTimeinSeconds) 1.0))
 (Variables|Default|SetPistolPoseUntil (+ (Utilities|Time|GetGameTimeinSeconds) 2.5))
 (if (Networking|HasAuthority)
  (bind (Roll Pitch Yaw) (Math|Rotator|BreakRotator (Pawn|GetControlRotation :self (Pawn|GetController))))
  (Transformation|SetActorRotation :NewRotation (Math|Rotator|MakeRotator :Yaw Yaw) :bTeleportPhysics false)))''')
B.remove_function_graph(bp,'GetDesiredGait')
g=B.add_function_graph(bp,'GetDesiredGait')
parent=next(n for n in B.find_nodes(g) if isinstance(n,unreal.K2Node_CallParentFunction))
result=next(n for n in B.find_nodes(g) if isinstance(n,unreal.K2Node_FunctionResult))
select_type=next(t for t in B.find_node_types(g,'Select',[]) if t.endswith('|Select'))
select=B.create_node(g,select_type,unreal.IntPoint(360,160))
aim=B.create_node(g,'Variables|Default|GetPublicAiming',unreal.IntPoint(100,300))
B.connect_pins(pin(aim,'PublicAiming',True),pin(select,'Index'))
B.break_pins(pin(parent,'ReturnValue',True),pin(result,'ReturnValue'))
B.connect_pins(pin(parent,'ReturnValue',True),pin(select,'Option 0'))
B.set_pin_value(pin(select,'Option 1'),'NewEnumerator0')
B.connect_pins(pin(select,'ReturnValue',True),pin(result,'ReturnValue'))
save(bp)
anim=asset('Combat/Animation/ABP_SurvivorCombat')
write(anim,'UpdatePistolLayer','''(fn UpdatePistolLayer (DeltaSeconds)
 (bind Pawn (Utilities|Casting|CastToBP_SurvivorInteractionCharacter (Animation|TryGetPawnOwner)))
 (bind Equipped (and (== (Class|BPSurvivorInteractionCharacter|GetPublicActiveSlot :self Pawn) 2) (== (Class|BPSurvivorInteractionCharacter|GetPublicSidearm :self Pawn) "Weapon.Pistol")))
 (bind Moving (> (Math|Vector|VectorLengthXY (Transformation|GetVelocity :self Pawn)) 150.0))
 (bind RecentShot (< (Utilities|Time|GetGameTimeinSeconds) (Class|BPSurvivorInteractionCharacter|GetPistolPoseUntil :self Pawn)))
 (bind Combat (or (Class|BPSurvivorInteractionCharacter|GetPublicAiming :self Pawn) (or (Class|BPSurvivorInteractionCharacter|GetPublicReloading :self Pawn) RecentShot)))
 (Variables|Default|SetPistolLayerWeight (Math|Interpolation|FInterpTo (Variables|Default|GetPistolLayerWeight) (select (and Equipped (or (not Moving) Combat)) 1.0 0.0) DeltaSeconds 10.0))
 (bind (Roll Pitch Yaw) (Math|Rotator|BreakRotator (Pawn|GetBaseAimRotation :self Pawn)))
 (Variables|Default|SetPistolAimPitch (/ (Math|Float|Clamp(Float) (Math|Rotator|NormalizeAxis Pitch) -85.0 85.0) 90.0)))''')
save(anim)
print('PISTOL_MOVEMENT_SAVED',str(backup))
